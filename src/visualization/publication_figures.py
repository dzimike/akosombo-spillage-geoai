# Fig 3 — Flood Class Statistics
# ────────────────────────────────────────────────────────────────────────────

def _flood_class_areas(flood_conf_p: Path) -> dict[str, float]:
    """Return km² per flood class from the confidence raster."""
    import rasterio
    with rasterio.open(flood_conf_p) as src:
        data = src.read(1)
        px_km2 = (src.res[0] * src.res[1]) / 1e6
    cls_map = {1: "SAR only", 2: "Optical only",
               3: "SAR + Optical agree", 4: "Permanent water"}
    return {label: int(np.sum(data == cls)) * px_km2
            for cls, label in cls_map.items()}


def fig3_flood_class_statistics(flood_conf_p: Path, out: Path) -> None:
    areas = _flood_class_areas(flood_conf_p)
    # Permanent water (JRC / open sea / pre-event optical) is not flood and is two
    # orders of magnitude larger than the flood classes: report it in the caption,
    # not in the bars or pie.
    keep   = [k for k in CLASS_COLORS if k != "Permanent water"]
    labels = keep
    values = [areas.get(k, 0) for k in labels]
    colors = [CLASS_COLORS[k] for k in labels]
    total  = sum(values)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

    # Panel A — horizontal bars
    y = np.arange(len(labels))
    bars = ax1.barh(y, values, color=colors, edgecolor="white", linewidth=0.5,
                    height=0.55)
    ax1.set_yticks(y)
    ax1.set_yticklabels(labels, fontsize=10)
    ax1.set_xlabel("Area (km²)", fontsize=10)
    ax1.set_title("A.  Flooded Area by Detection Class", fontsize=10,
                  fontweight="bold")
    ax1.xaxis.set_major_formatter(mticker.FuncFormatter(
        lambda v, _: f"{v:,.1f}"))
    ax1.grid(axis="x", linestyle=":", alpha=0.4)
    for bar, val, lbl in zip(bars, values, labels):
        pct = 100 * val / total if total > 0 else 0
        ax1.text(bar.get_width() + total * 0.01,
                 bar.get_y() + bar.get_height() / 2,
                 f"{val:,.1f} km²  ({pct:.1f}%)",
                 va="center", fontsize=9)
    ax1.set_xlim(0, max(values) * 1.35)
    ax1.spines[["top", "right"]].set_visible(False)

    # Panel B — pie
    wedge_props = dict(edgecolor="white", linewidth=1.5)
    wedges, texts, autotexts = ax2.pie(
        values, labels=None, colors=colors,
        autopct="%1.1f%%", pctdistance=0.7,
        startangle=90, counterclock=False,
        wedgeprops=wedge_props,
        textprops={"fontsize": 9})
    ax2.legend(wedges, labels, loc="center left", bbox_to_anchor=(1.0, 0.5),
               fontsize=9, frameon=False)
    for at in autotexts:
        at.set_fontsize(9)
        at.set_fontweight("bold")
        at.set_color("white")
    ax2.set_title(
        f"B.  Composition of the Flooded Area\n"
        f"(Total: {total:,.1f} km²)",
        fontsize=10, fontweight="bold")

    fig.text(0.5, 0.01,
             "Source: Sentinel-1 SAR + Sentinel-2 optical fusion  |  10 m resolution",
             ha="center", fontsize=7, color="grey")
    fig.tight_layout(rect=[0, 0.04, 1, 1])
    fig.savefig(out, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    log.info("Fig 3 saved: %s", out)


