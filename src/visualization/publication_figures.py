def main(config_path: str | None = None) -> None:
    proj_root  = get_project_root()
    config     = load_config(config_path)
    figs_dir   = get_output_path("figures", config)
    tables_dir = get_output_path("tables",  config)
    models_dir = get_output_path("models",  config)
    ensure_dir(figs_dir)

    flood_conf_p    = get_processed_path(
                        "flood_extent/fused_flood_confidence.tif", config)
    xgb_model_p     = models_dir / "xgb_flood_model.joblib"
    rf_model_p      = models_dir / "rf_flood_model.joblib"
    xgb_metrics_p   = tables_dir / "xgb_metrics.csv"
    rf_metrics_p    = tables_dir / "rf_metrics.csv"
    threshold_p     = tables_dir / "threshold_sensitivity.csv"

    outputs = []
    with Timer() as t:
        # Fig 2 — workflow
        p = figs_dir / "fig2_methodological_workflow.png"
        make_workflow_diagram(p)
        outputs.append(p)

        # Fig 3 — flood class statistics
        if flood_conf_p.exists():
            p = figs_dir / "fig3_flood_class_statistics.png"
            fig3_flood_class_statistics(flood_conf_p, p)
            outputs.append(p)
        else:
            log.warning("Flood confidence raster not found; skipping fig 3")

        # Fig 4 — exposure hotspots: generated by make_fig4_exposure() in
        # regenerate_24_figures.py, not this module. See note above where
        # fig4_exposure_hotspots() used to live.

        # Fig 5 — feature importance
        p = figs_dir / "fig5_feature_importance.png"
        fig5_feature_importance(xgb_model_p, rf_model_p, p)
        outputs.append(p)

        # Fig 6 — model performance
        p = figs_dir / "fig6_model_performance.png"
        fig6_model_performance(xgb_metrics_p, rf_metrics_p, threshold_p, p)
        outputs.append(p)

        # Fig 7 — recovery analysis: generated by make_fig7_recovery() in
        # regenerate_24_figures.py, not this module. See note above where
        # fig7_recovery_analysis() used to live.

    log.info("Publication figures complete in %.1f s  (%d figures)",
             t.elapsed, len(outputs))
    log_run(
        script=__file__,
        input_paths=[],
        output_paths=[str(o) for o in outputs],
        parameters={"dpi": DPI, "n_figures": len(outputs)},
        status="success", runtime_seconds=t.elapsed,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate publication figures")
    parser.add_argument("--config", default=None)
    main(parser.parse_args().config)
