# Figure 2 — Threshold sensitivity: precision/recall/F1 + flood coverage
# ---------------------------------------------------------------------------

def make_fig2(out_path: Path) -> None:
    log.info("Figure 2: threshold sensitivity curves…")

    df = pd.read_csv(_tables() / "threshold_sensitivity.csv")

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4.2), dpi=DPI)

    # --- Panel (a): Precision / Recall / F1 ---
    ax1.plot(df.threshold, df.precision, color=PRF["precision"], lw=2.0,
             label="Precision")
    ax1.plot(df.threshold, df.recall,    color=PRF["recall"], ls="--", lw=2.0,
             label="Recall")
    ax1.plot(df.threshold, df.f1,        color=PRF["f1"], lw=2.0,
             ls="--", label="F1")

    best = df.loc[(df.threshold - THR_OPT).abs().idxmin()]
    ax1.axvline(best.threshold, color=PRF["f1"], lw=0.9, ls=":",
                alpha=0.7, label=f"Validation-selected (thr={best.threshold:.2f})")
    ax1.axvline(THR_REF, color="#757575", lw=0.9, ls="--",
                alpha=0.7, label=f"Reference (thr={THR_REF})")

    ax1.annotate(f"Test F1 = {best.f1:.3f}\nthr = {best.threshold:.2f}",
                 xy=(best.threshold, best.f1),
                 xytext=(best.threshold + 0.06, best.f1 - 0.025),
                 fontsize=6.5,
                 arrowprops=dict(arrowstyle="->", color=PRF["f1"], lw=0.8),
                 color=PRF["f1"])

    ax1.set_xlabel("Decision threshold", fontsize=8)
    ax1.set_ylabel("Score", fontsize=8)
    ax1.set_title("(a) Precision, Recall and F1 vs threshold", fontsize=8, pad=6)
    ax1.set_xlim(0.05, 0.95); ax1.set_ylim(0.85, 1.005)
    ax1.legend(fontsize=6.5, loc="lower left", framealpha=0.85)
    ax1.grid(True, lw=0.4, alpha=0.4)
    ax1.tick_params(labelsize=7)
    ax1.spines[["top", "right"]].set_visible(False)

    # --- Panel (b): direct full-scene flood area vs threshold (raw and prior-corrected) ---
    raw, cor = load_direct(False), load_direct(True)
    ax2.plot(raw.threshold, raw.flood_area_km2, color=CALIBRATION["raw"], lw=2.0, label="Raw classifier score")
    ax2.plot(cor.threshold, cor.flood_area_km2, color=CALIBRATION["corrected"], lw=2.0, label="Prior-corrected probability")
    ax2.axhline(REF_AREA, color=DEFINITION["change"], lw=0.9, ls="-.", alpha=0.8, label=f"Fused map ({REF_AREA:.1f} km²)")
    ax2.set_yscale("log")
    ax2.set_xlabel("Decision threshold", fontsize=8)
    ax2.set_ylabel("Flood area, full scene (km², log axis)", fontsize=8)
    ax2.tick_params(labelsize=7)
    ax2.axvline(THR_REF, color="#757575", lw=0.9, ls="--", alpha=0.7)
    for d_, c_ in ((raw, CALIBRATION["raw"]), (cor, CALIBRATION["corrected"])):
        for t_ in (0.05, 0.50, 0.95):
            v = float(d_.loc[d_.threshold == t_, "flood_area_km2"].iloc[0])
            ax2.plot(t_, v, "o", color=c_, ms=3.5)
            ax2.annotate(f"{v:.0f}", xy=(t_, v), xytext=(4, 4), textcoords="offset points", fontsize=6, color=c_)
    ax2.set_title("(b) Flood area vs threshold, full scene", fontsize=8, pad=6)
    ax2.set_xlim(0.05, 0.95)
    ax2.grid(True, lw=0.4, alpha=0.4, which="both")
    ax2.spines[["top", "right"]].set_visible(False)
    ax2.legend(fontsize=6, loc="upper right", framealpha=0.85)

    fig.tight_layout()
    fig.savefig(out_path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    log.info("  Saved: %s", out_path)


