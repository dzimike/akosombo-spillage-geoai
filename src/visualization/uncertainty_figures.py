"""
Uncertainty Manuscript Figure Generator
=========================================
Produces the five publication figures for the uncertainty propagation paper
targeting Natural Hazards and Earth System Sciences.

Figures produced (all → outputs/figures/uncertainty_paper/ at 300 DPI)
-----------------------------------------------------------------------
fig2_threshold_sensitivity.png     — precision/recall/F1 and flood coverage vs threshold
fig3_exposure_propagation.png      — exposure metrics across the full threshold sweep

fig1_study_area_flood_extent.png, fig4_recovery_rank_stability.png, and
fig5_uncertainty_decomposition.png are NOT produced by this module — they
are generated by make_uncertainty_fig1(), make_ufig4_rank_stability(), and
make_ufig5_decomposition() in regenerate_24_figures.py (project root). Run
`python regenerate_24_figures.py` for those three.

Usage
-----
    python -m src.visualization.uncertainty_figures
    python -m src.visualization.uncertainty_figures --only fig2 fig3
"""

