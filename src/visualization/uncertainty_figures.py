# Figure 3 — Exposure propagation across threshold range
# ---------------------------------------------------------------------------

def make_fig3(out_path: Path) -> None:
    log.info("Figure 3: direct exposure propagation (raw and prior-corrected)…")

    raw, cor = load_direct(False).set_index("threshold"), load_direct(True).set_index("threshold")
    fig, axes = plt.subplots(1, 3, figsize=(12, 4.2), dpi=DPI)
    fig.subplots_adjust(wspace=0.32)
    pairs = [
        (axes[0], "buildings_exposed", "Buildings exposed",    ASSET["buildings"], "{:.0f}"),
        (axes[1], "population_exposed", "Population exposed",  ASSET["people"], "{:.0f}"),
        (axes[2], "roads_exposed_km",  "Roads inundated (km)", ASSET["roads"], "{:.1f}"),
    ]
    for ax, col, ylabel, color, fmt in pairs:
        ax.plot(cor.index, cor[col], color=color, lw=2.0, label="Prior-corrected probability")
        ax.fill_between(cor.index, cor[col], alpha=0.12, color=color)
        ax.plot(raw.index, raw[col], color=CALIBRATION["raw"], lw=1.6, ls="--", label="Raw classifier score")
        ref = float(cor.loc[THR_REF, col])
        ax.plot(THR_REF, ref, "o", color=color, ms=7, zorder=5, label=f"Corrected 0.50 ({fmt.format(ref)})")
        hp = cor[col].loc[THR_REF:0.95]
        ax.annotate(f"Corrected 0.50–0.95: {fmt.format(hp.min())} – {fmt.format(hp.max())}\n"
                    f"({100 * (hp.max() - hp.min()) / ref:.0f}% of 0.50 value)\n"
                    f"Raw 0.50–0.95: {fmt.format(raw[col].loc[0.5:0.95].min())} – {fmt.format(raw[col].loc[0.5:0.95].max())}",
                    xy=(0.97, 0.97), xycoords="axes fraction", ha="right", va="top", fontsize=6.0,
                    bbox=dict(boxstyle="round,pad=0.3", fc="white", ec=color, lw=0.7, alpha=0.9))
        ax.set_yscale("log")
        ax.axvline(THR_REF, color="#757575", lw=0.8, ls="--", alpha=0.6)
        ax.set_xlabel("Decision threshold", fontsize=8)
        ax.set_ylabel(ylabel + " (log axis)", fontsize=8)
        ax.tick_params(labelsize=7)
        ax.grid(True, lw=0.4, alpha=0.4, which="both")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(fontsize=5.5, loc="lower left", framealpha=0.85)
        ax.set_xlim(0.05, 0.95)
    fig.savefig(out_path, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    log.info("  Saved: %s", out_path)


