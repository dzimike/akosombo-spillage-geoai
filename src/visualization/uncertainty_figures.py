logging.basicConfig(level=logging.INFO,
                    format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger(__name__)

DPI = 300

# Reference and optimal thresholds
THR_REF  = 0.50


def _selected_threshold(default: float = 0.75) -> float:
    """Decision threshold selected on the validation blocks (uncertainty_summary.csv)."""
    try:
        s = pd.read_csv(get_project_root() / "outputs/tables/uncertainty_summary.csv")
        return float(s.loc[s.metric == "optimal_threshold", "value"].iloc[0])
    except Exception:
        return default


def _fused_area_km2(root) -> float:
    """Land flood area (classes 1-3) of the current fused map, from fused_flood_stats.csv."""
    import csv
    with open(root / "data/processed/flood_extent/fused_flood_stats.csv") as f:
        for r in csv.DictReader(f):
            if r["class"] == "total_flooded_all_sources":
                return float(r["area_km2"])
    raise KeyError("total_flooded_all_sources")


THR_OPT  = _selected_threshold()
REF_AREA = _fused_area_km2(get_project_root())   # km², fused flood confidence map (classes 1-3)

# The old proportional-scaling approximation (exposure at threshold t = reference
# exposure x test-partition flood coverage at t / coverage at 0.50) is drawn only
# as a comparison curve in Figure 3; the 0.50 coverage is read from
# threshold_sensitivity.csv so it always matches the current model and test split.

# Direct full-scene exposure (outputs/tables/threshold_exposure_direct.csv)
# uses the 426,499-person clipped WorldPop grid; the paper's AOI total is
# 366,077, so population is scaled by a uniform factor for presentation.
POP_SCALE = 366077 / 426499


# ---------------------------------------------------------------------------
# Path helpers
# ---------------------------------------------------------------------------

def _proj() -> Path:
    return get_project_root()

def _tables() -> Path:
    return _proj() / "outputs" / "tables"

def _maps() -> Path:
    return _proj() / "outputs" / "maps"

def load_direct(corrected: bool = False) -> pd.DataFrame:
    """Direct full-scene threshold->exposure table (population on the paper's AOI scale).

    corrected=True reads the sweep on the prior-shift-corrected probability (validation/prior_correct_probability.py)."""
    d = pd.read_csv(_tables() / ("threshold_exposure_direct_prior_corrected.csv" if corrected
                                 else "threshold_exposure_direct.csv"))
    d["population_exposed"] = d["population_exposed"] * POP_SCALE
    return d


def _out_dir() -> Path:
    d = _proj() / "outputs" / "figures" / "uncertainty_paper"
    ensure_dir(d)
    return d


