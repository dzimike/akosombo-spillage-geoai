# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main(only: list[str] | None = None) -> None:
    import os
    os.chdir(_proj())

    out     = _out_dir()
    targets = only if only else list(FIGURES.keys())

    with Timer() as t:
        for key in targets:
            if key not in FIGURES:
                log.warning("Unknown figure key: %s", key)
                continue
            fn, stem = FIGURES[key]
            path = out / f"{stem}.png"
            try:
                fn(path)
            except Exception as exc:
                log.error("Figure %s failed: %s", key, exc, exc_info=True)

    log_run(
        script=__file__,
        input_paths=[str(_tables()), str(_maps())],
        output_paths=[str(out)],
        parameters={"figures": targets},
        status="success",
        runtime_seconds=t.elapsed,
    )
    log.info("All figures complete in %.1f s → %s", t.elapsed, out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Generate uncertainty manuscript figures (Figures 1-5)")
    parser.add_argument("--only", nargs="+", metavar="fig1",
                        help="Generate only the specified keys")
    args = parser.parse_args()
    main(args.only)
