def load_style(proj_root: Path) -> dict:
    with open(proj_root / "config" / "map_style.yaml") as f:
        return yaml.safe_load(f)


def read_raster(path: Path, band: int = 1):
    """Return (array, transform, crs, bounds) for a single band."""
    with rasterio.open(path) as src:
        arr       = src.read(band).astype(np.float32)
        nd        = src.nodata
        transform = src.transform
        crs       = src.crs
        bounds    = src.bounds
    if nd is not None:
        arr = np.where(arr == nd, np.nan, arr)
    return arr, transform, crs, bounds


def raster_extent(bounds):
    """Return [left, right, bottom, top] for imshow extent."""
    return [bounds.left, bounds.right, bounds.bottom, bounds.top]


def add_basemap(ax, crs=PROJ_CRS):
    """Add Esri World Light Gray basemap (CARTO tiles now require an API key)."""
    try:
        import contextily as ctx
        ctx.add_basemap(ax, crs=crs, source=ctx.providers.Esri.WorldGrayCanvas,
                        attribution_size=6, zoom="auto", zorder=0)
    except Exception as e:
        log.warning("Basemap unavailable: %s", e)


def add_scalebar(ax):
    try:
        from matplotlib_scalebar.scalebar import ScaleBar
        ax.add_artist(ScaleBar(1, units="m", location="lower right",
                               length_fraction=0.20, border_pad=0.5,
                               font_properties={"size": 8}))
    except Exception as e:
        log.warning("Scale bar failed: %s", e)


def add_north_arrow(ax, x=0.95, y=0.95, size=0.05):
    ax.annotate("N", xy=(x, y), xytext=(x, y - size),
                xycoords="axes fraction",
                ha="center", va="bottom", fontsize=10, fontweight="bold",
                arrowprops=dict(arrowstyle="-|>", color="black", lw=1.5))


def plot_communities(ax, gdf: gpd.GeoDataFrame, label_col="community_name",
                     offset=(4000, 2000)):
    gdf = gdf.to_crs(PROJ_CRS)
    gdf.plot(ax=ax, color="white", edgecolor="black",
             marker="*", markersize=100, zorder=6)
    for _, row in gdf.iterrows():
        ax.annotate(row[label_col],
                    xy=(row.geometry.x, row.geometry.y),
                    xytext=(row.geometry.x + offset[0], row.geometry.y + offset[1]),
                    fontsize=7, fontweight="bold", color="black",
                    bbox=dict(boxstyle="round,pad=0.2", fc="white", alpha=0.7, lw=0.4),
                    arrowprops=dict(arrowstyle="-", color="black", lw=0.5))


def style_ax(ax, title: str, style: dict):
    ax.set_title(title, fontsize=style["figure"]["title_size"],
                 fontweight="bold", pad=6)
    ax.set_xlabel("Easting (m)", fontsize=8)
    ax.set_ylabel("Northing (m)", fontsize=8)
    ax.tick_params(labelsize=7)
    for spine in ax.spines.values():
        spine.set_linewidth(0.5)


