# Map 1 — Flood Extent
# ---------------------------------------------------------------------------

def map_flood_extent(proj_root: Path, style: dict, out_dir: Path) -> Path:
    log.info("Drawing flood extent map…")
    flood_p = get_processed_path("flood_extent/fused_flood_confidence.tif")
    comm_p  = get_processed_path("aoi/affected_communities.gpkg")
    aoi_p   = get_processed_path("aoi/lower_volta_aoi.gpkg")

    arr, tf, crs, bounds = read_raster(flood_p, band=1)

    # Class colours and alpha values.
    # Class 0 (not flooded) is fully transparent so the basemap shows through.
    class_styles = {
        1: ("#90CAF9", 0.75),   # SAR only             — light blue
        2: ("#42A5F5", 0.75),   # optical only         — medium blue
        3: ("#1565C0", 0.85),   # SAR + optical agree  — dark blue
        4: ("#0D47A1", 0.95),   # permanent water      — navy
        # class 0 (not flooded) and class 9 (nodata) → alpha = 0 (transparent)
    }
    rgba = np.zeros((*arr.shape, 4), dtype=np.float32)   # all transparent
    for cls, (hex_col, alpha) in class_styles.items():
        mask = (arr == cls)
        r, g, b, _ = mcolors.to_rgba(hex_col)
        rgba[mask] = [r, g, b, alpha]

    fig, ax = plt.subplots(figsize=(style["figure"]["width_inches"],
                                    style["figure"]["height_inches"]))

    # imshow first so axes extent is set; basemap added after at zorder=0 (behind)
    ax.imshow(rgba, extent=raster_extent(bounds), origin="upper",
              interpolation="nearest", zorder=2)
    add_basemap(ax, crs=str(crs))

    if aoi_p.exists():
        gpd.read_file(aoi_p).to_crs(PROJ_CRS).boundary.plot(
            ax=ax, color="black", linewidth=0.8, linestyle="--", zorder=4)
    if comm_p.exists():
        plot_communities(ax, gpd.read_file(comm_p))

    add_scalebar(ax)
    add_north_arrow(ax)

    # ---- Legend: every visible symbol is represented ----------------------
    legend_handles = [
        mpatches.Patch(facecolor="#90CAF9", alpha=0.75, edgecolor="none",
                       label="SAR only"),
        mpatches.Patch(facecolor="#42A5F5", alpha=0.75, edgecolor="none",
                       label="Optical only"),
        mpatches.Patch(facecolor="#1565C0", alpha=0.85, edgecolor="none",
                       label="SAR + Optical agreement"),
        mpatches.Patch(facecolor="#0D47A1", alpha=0.95, edgecolor="none",
                       label="Permanent water"),
        Line2D([0], [0], color="black", lw=0.8, linestyle="--",
               label="AOI boundary"),
        Line2D([0], [0], marker="*", color="w",
               markerfacecolor="white", markeredgecolor="black",
               markersize=9, lw=0, label="Community"),
    ]
    ax.legend(handles=legend_handles, loc="lower left", fontsize=7,
              framealpha=0.88, title="Flood class", title_fontsize=7)

    style_ax(ax, "Fused Flood Extent — Akosombo Dam Spillage 2023\n"
             "Sep–Nov 2023 · Lower Volta Basin, Ghana", style)
    ax.text(0.01, 0.01, "Data: Sentinel-1/2 · GEE · CRS: EPSG:32630",
            transform=ax.transAxes, fontsize=6, color="grey", va="bottom")

    fig.tight_layout()
    out = out_dir / "pub_flood_extent_map.png"
    fig.savefig(out, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    log.info("  Saved: %s", out)
    return out


