def main(config_path: str | None = None) -> None:
    proj_root = get_project_root()
    config    = load_config(config_path)
    style     = load_style(proj_root)
    out_dir   = get_output_path("maps", config)
    ensure_dir(out_dir)

    plt.rcParams.update({
        "font.family":  style["figure"]["font_family"],
        "font.size":    style["figure"]["font_size"],
        "axes.linewidth": 0.6,
    })

    outputs = []
    with Timer() as t:
        outputs.append(map_flood_extent(proj_root, style, out_dir))
        outputs.append(map_susceptibility(proj_root, style, out_dir))
        # pub_exposure_summary.png and pub_recovery_dashboard.png: generated
        # by regenerate_24_figures.py, not this module. See notes above.

    log.info("All publication maps complete in %.1f s", t.elapsed)
    log_run(
        script=__file__,
        input_paths=[],
        output_paths=[str(o) for o in outputs if o],
        parameters={"dpi": DPI, "n_maps": len([o for o in outputs if o])},
        status="success", runtime_seconds=t.elapsed,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Publication-quality static maps")
    parser.add_argument("--config", default=None)
    main(parser.parse_args().config)
