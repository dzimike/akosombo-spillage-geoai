# Map 2 — Susceptibility
# ---------------------------------------------------------------------------

def map_susceptibility(proj_root: Path, style: dict, out_dir: Path) -> Path:
    log.info("Drawing susceptibility map…")
    susc_p  = proj_root / "outputs/maps/flood_susceptibility_xgb.tif"
    flood_p = get_processed_path("flood_extent/fused_flood_extent.gpkg")
    comm_p  = get_processed_path("aoi/affected_communities.gpkg")

    if not susc_p.exists():
        log.warning("Susceptibility raster not found; skipping"); return None

    arr, tf, crs, bounds = read_raster(susc_p)
    # Permanent water (JRC class 4, incl. the Gulf of Guinea) is scored p~0.85 by
    # the classifier but is not flood-prone land: draw it as masked water.
    fused_p = get_processed_path("flood_extent/fused_flood_confidence.tif")
    perm = None
    if fused_p.exists():
        with rasterio.open(fused_p) as fsrc:
            if fsrc.shape == arr.shape:
                perm = fsrc.read(1) == 4
                arr = np.where(perm, np.nan, arr)
    masked = np.ma.masked_invalid(arr)
    _m = pd.read_csv(proj_root / "outputs/tables/xgb_metrics.csv")
    auc = float(_m.loc[_m.split == "test", "roc_auc"].iloc[0])

    # Use plt.colormaps[] (replaces deprecated plt.cm.get_cmap)
    cmap_name = style["colormaps"]["susceptibility"]   # "RdYlGn_r"
    cmap = plt.colormaps[cmap_name].copy()
    cmap.set_bad("lightgrey", alpha=0.3)

    fig, ax = plt.subplots(figsize=(style["figure"]["width_inches"],
                                    style["figure"]["height_inches"]))

    # imshow first so axes extent is set; basemap added after at zorder=0 (behind)
    im = ax.imshow(masked, extent=raster_extent(bounds), origin="upper",
                   cmap=cmap, vmin=0, vmax=1, interpolation="bilinear",
                   alpha=0.75, zorder=2)
    add_basemap(ax, crs=str(crs))
    if perm is not None:
        water = np.ma.masked_where(~perm, np.ones(perm.shape, np.uint8))
        ax.imshow(water, extent=raster_extent(bounds), origin="upper",
                  cmap=ListedColormap(["#9ECAE1"]), alpha=0.9, zorder=3,
                  interpolation="nearest")

    has_flood_boundary = False
    if flood_p.exists():
        gpd.read_file(flood_p).to_crs(PROJ_CRS).boundary.plot(
            ax=ax, color="#1565C0", linewidth=0.8, alpha=0.85, zorder=4)
        has_flood_boundary = True

    has_comm = comm_p.exists()
    if has_comm:
        plot_communities(ax, gpd.read_file(comm_p))

    add_scalebar(ax)
    add_north_arrow(ax)

    # ---- Colourbar --------------------------------------------------------
    cbar = fig.colorbar(im, ax=ax, fraction=0.03, pad=0.02, shrink=0.75)
    cbar.set_label("Flood Susceptibility Probability", fontsize=8)
    cbar.ax.tick_params(labelsize=7)

    # ---- Legend: one handle per visible non-raster symbol -----------------
    legend_handles = []
    if has_flood_boundary:
        legend_handles.append(
            Line2D([0], [0], color="#1565C0", lw=1.5, alpha=0.85,
                   label="Observed flood extent")
        )
    if has_comm:
        legend_handles.append(
            Line2D([0], [0], marker="*", color="w",
                   markerfacecolor="white", markeredgecolor="black",
                   markersize=9, lw=0, label="Community")
        )
    if perm is not None:
        legend_handles.append(Patch(facecolor="#9ECAE1", edgecolor="none",
                                    label="Permanent water / sea (masked)"))
    if legend_handles:
        ax.legend(handles=legend_handles, loc="lower left", fontsize=7,
                  framealpha=0.88)

    style_ax(ax, "Flood Susceptibility — XGBoost Model\n"
             "Akosombo Spillage 2023 · Lower Volta Basin, Ghana", style)
    ax.text(0.5, 0.005, f"Model: XGBoost · test ROC-AUC {auc:.4f} · CRS: EPSG:32630",
            transform=ax.transAxes, fontsize=6, color="dimgrey", va="bottom",
            ha="center", zorder=10)

    fig.tight_layout()
    out = out_dir / "pub_susceptibility_map.png"
    fig.savefig(out, dpi=DPI, bbox_inches="tight")
    plt.close(fig)
    log.info("  Saved: %s", out)
    return out


